/* ── السورةُ المسمّاة في نصٍّ حرّ ─────────────────────────────
   عقدُ التأليف يكتب سورةَ النصّ في عنوانه أو وصفه نصّاً حرّاً (188 · الرأس): «من أجل حياةٍ كريمة
   (سورة الأنعام ١٥١–١٥٢)». فيقرأها المحدِّدُ ليقترحها — **اقتراحاً يراه المعلّمُ قبل الحفظ، لا حكماً.**
   📐 والقراءةُ بعد «سورة» وحدها، بعد نزع التشكيل وتوحيد صور الحرف — تطبيعُ `normAr` في book.js، ومعه
      الهمزةُ على الواو والياء: «المومنون» تُكتب هكذا أحياناً. والاسمُ أطولُ ما طابق: «حم السجدة» لا «السجدة».
   🔑 **وما يُلبِس لا يُقرأ:** «سورتا الفلق والناس» و«سور» جمعٌ لا تُعرف به سورةُ كتلة ⇒ null. و«سورة العصر
      والإخلاص» سورتان لا واحدة — الواوُ تعطف اسماً ثانياً فيُعدّ. فالاقتراحُ يسقط حيث سُمّيت سورتان،
      ولا تُقترح سورةٌ لآيةٍ من أختها. */
const MARKS = /[ً-ٰٟۖ-ۭـ]/g;
const norm = s => String(s || '').replace(MARKS, '').replace(/[أإآٱ]/g, 'ا')
  .replace(/ى/g, 'ي').replace(/ة/g, 'ه').replace(/ؤ/g, 'و').replace(/ئ/g, 'ي');
const words = s => norm(s).split(/[^\p{L}]+/u).filter(Boolean);

/* أسماءٌ أخرى تُكتب بها السورة — للقراءة وحدها، والقائمةُ تعرض اسمَ المصحف */
const ALIAS = {
  1: ['الحمد'], 9: ['براءة'], 17: ['بني إسرائيل'], 36: ['ياسين'], 38: ['صاد'], 40: ['المؤمن'],
  41: ['حم السجدة'], 47: ['القتال'], 50: ['قاف'], 68: ['ن', 'نون'], 76: ['الدهر'], 83: ['التطفيف'],
  94: ['الانشراح', 'ألم نشرح'], 99: ['الزلزال'], 111: ['اللهب', 'تبت'], 112: ['التوحيد']
};
const NAMES = SURAHS.flatMap(([name], i) => [name, ...(ALIAS[i + 1] || [])].map(x => [words(x), i + 1]))
  .sort((a, b) => b[0].length - a[0].length);
const nameAt = t => NAMES.find(([w]) => w.every((x, j) => t[j] === x));

const ONE  = /^[وفبلك]?سوره$/;
const MANY = /^[وفبلك]?(?:ال)?سور(?:تا|تي|تين|تان)?$/;

/* ⇒ أرقامُ السور المسمّاة بلا تكرار ([] إن لم تُسمَّ سورة) · أو null إن جاء الجمع */
export function surahsNamed(text){
  const t = words(text), out = new Set();
  for(let i = 0; i < t.length; i++){
    if(MANY.test(t[i])) return null;
    if(!ONE.test(t[i])) continue;
    let rest = t.slice(i + 1), hit = nameAt(rest);
    while(hit){
      out.add(hit[1]);
      rest = rest.slice(hit[0].length);
      if(!rest[0]?.startsWith('و')) break;
      rest = [rest[0].slice(1), ...rest.slice(1)];
      hit = nameAt(rest);
    }
  }
  return [...out];
}
