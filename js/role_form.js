/* 🔑 ومفرداتُ الصيغة تتبع الدور، ولا يُقال «مذكّر · مؤنّث»: المسجِّلُ
   يقرأ عن نفسِه لا عن خانةٍ في استمارة. وهي المفردات نفسُها التي يراها
   بعدُ في قائمة حسابه (`gramAsk` · ui.js) — **ومفردةٌ ثانية لشيءٍ واحد
   تُقرأ شيئاً آخر.** */
const GRAMS = {
  student: [['m', 'أنا طالب'],  ['f', 'أنا طالبة']],
  teacher: [['m', 'أنا معلّم'], ['f', 'أنا معلّمة']]
};

/* ⚠️ و`picked` تقول «وقعت نقرةٌ على الدور» لا «الدورُ معروف»: قيمتُه
   الافتراضية 'student' معروفةٌ دائماً، وهي حقولٌ لا اختيار. ووجودُ صيغةٍ
   محفوظة يُغني عنها — فمن له صيغةٌ قد اختار دورَه بالضرورة. */
export const roleTabs = (role = 'student', picked = false) => {
  const r   = role === 'teacher' ? 'teacher' : 'student';
  return `
  <div id="rf_tabs" class="rf-roles" role="group" aria-label="دورك">
    ${ROLES.map(([rr, label]) =>
      `<button type="button" class="btn ${picked && r === rr ? 'primary' : 'ghost'}"
               data-role="${rr}" aria-pressed="${picked && r === rr}">${label}</button>`
    ).join('')}
  </div>`;
};

/* 🔑 المنسدلة — **عنوانٌ وخياران ولا سطرَ ثالث**. و«— اختر —» أوّلاً فلا
   افتراضَ مذكّر. ومفرداتُها تتبع الدور، وهي مفرداتُ قائمة الحساب نفسُها
   (`gramAsk` · ui.js) — **ومفردةٌ ثانية لشيءٍ واحد تُقرأ شيئاً آخر.** */
export const gramSelect = (role = 'student', g = null) => {
  const r = role === 'teacher' ? 'teacher' : 'student';
  return `
  <div id="rf_gram" style="margin-top:16px">
    <label class="fl" for="rf_g">كيف نخاطبك؟</label>
    <select id="rf_g">
      <option value="" ${g ? '' : 'selected'}>— اختر —</option>
      ${GRAMS[r].map(([gg, label]) =>
        `<option value="${gg}" ${g === gg ? 'selected' : ''}>${label}</option>`).join('')}
    </select>
  </div>`;
};

/* يُركَّب مرّةً على الحاوية، ويُنادي onPick(role) عند النقر.
   📌 وتبديلُ الدور **يُبقي الصيغة**: من اختار «أنا طالبة» ثمّ صحّح دورَه
      لم تتغيّر صيغتُه، وإلغاؤها تسألُه مرّتين عن شيءٍ واحد. والمفرداتُ
      وحدها تتبدّل، والقيمةُ `m/f` باقيةٌ في الحالة. */
export function wireRoleTabs(root, onPick){
  const box = root.querySelector('#rf_tabs'); if(!box) return;
  box.querySelectorAll('[data-role]').forEach(b => b.onclick = () => {
    if(b.getAttribute('aria-pressed') === 'true') return;   // لا رسمَ بلا تغيير
    onPick(b.dataset.role);
  });
}

/* 🔴 **ولا إعادةَ رسمٍ عند تغيير الصيغة — وهذا حارسٌ لا تحسين.** نقرةُ
   الصيغة تقع **بعد** كلمة المرور الآن، و`renderGate` تُعيد البناء
   و`keepDraft` لا تحفظ المرورَ عمداً (ولا مربّعَ الموافقة) ⇒ إعادةُ
   الرسم كانت تمحو ما كُتب **تحت عين صاحبه وبلا خبر**. والمنسدلةُ لا
   تُغيّر في الشاشة شيئاً سوى قيمتِها، فلا رسمَ لها أصلاً. */
export function wireGram(root, onPick){
  const sel = root.querySelector('#rf_g'); if(!sel) return;
  sel.onchange = () => onPick(sel.value || null);
}

