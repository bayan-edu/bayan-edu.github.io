import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const UI = join(dirname(fileURLToPath(import.meta.url)), '..', 'js', 'ui.js');
const src = readFileSync(UI, 'utf8');

/* يُقتطع جسمُ الدالّة وحدَه: ui.js وحدةٌ تستورد media/avatar، واستيرادُها
   في node يجرّ المتصفّحَ كلَّه. والمقتطَعُ نصُّها حرفاً. */
const cut = src.match(/export function backMeta\(back\)\{[\s\S]*?\n\}/);
if(!cut) { console.error('✗ لم يُعثر على backMeta في js/ui.js — تغيّر توقيعُها؟'); process.exit(1); }
const backMeta = new Function(cut[0].replace('export function backMeta', 'return function'))();

let pass = 0, fail = 0;
const t = (name, back, wantMain, wantMeta) => {
  const [main, meta] = backMeta(back);
  const open = (main.match(/\(/g) || []).length, close = (main.match(/\)/g) || []).length;
  const ok = main === wantMain && meta === wantMeta && open === close;
  if(ok) { pass++; return; }
  fail++;
  console.error(`✗ ${name}`);
  if(main !== wantMain) console.error(`   المتن  = ${JSON.stringify(main)}\n   المنتظر = ${JSON.stringify(wantMain)}`);
  if(meta !== wantMeta) console.error(`   الملحق = ${JSON.stringify(meta)}\n   المنتظر = ${JSON.stringify(wantMeta)}`);
  if(open !== close)    console.error(`   🔴 أقواسُ المتن غير متوازنة: ${open} مفتوحاً و${close} مغلقاً`);
};

/* ── ① يُفصل: قوسٌ ختاميٌّ فيه نقطتان ── */
t('عربيّة · فاصلُ الملحق «·»',
  'التَّظاهُرُ بالعَمَى والتَّغافُلُ النَّبيلُ عن العَثَرات (المضاد: التَّفْتيش والتَّرَصُّد)',
  'التَّظاهُرُ بالعَمَى والتَّغافُلُ النَّبيلُ عن العَثَرات',
  'المضاد: التَّفْتيش والتَّرَصُّد');

t('عربيّة · فاصلُ الملحق «؛» — ولا يُعاد تقطيعُه',
  'حِبالٌ مَشْدودةٌ تُثبَّتُ بها أوتادُ الخَيمة (حبالٌ تُشَدّ بها؛ المفرد: طُنُب)',
  'حِبالٌ مَشْدودةٌ تُثبَّتُ بها أوتادُ الخَيمة',
  'حبالٌ تُشَدّ بها؛ المفرد: طُنُب');

t('إنجليزيّة · Syn/Ant والمتنُ يبقى لـbackText',
  'حَضارة · an organized society with advanced culture (Syn: developed society | Ant: barbarism)',
  'حَضارة · an organized society with advanced culture',
  'Syn: developed society | Ant: barbarism');

/* ── ② لا يُفصل: قوسٌ ختاميٌّ بلا نقطتين — وهو صُلبُ المعنى ── */
t('تاريخٌ في الذيل — ٥٢ بطاقةً تقف على هذه',
  'من فتح القسطنطينية (١٤٥٣م) حتى اندلاع الحرب العالمية الأولى (١٩١٤م)',
  'من فتح القسطنطينية (١٤٥٣م) حتى اندلاع الحرب العالمية الأولى (١٩١٤م)', '');

t('أسرةٌ في الذيل',
  'حقبةُ تفكّكٍ تلت الدولة القديمة، وتشمل الأسرات (٧ – ١٠)',
  'حقبةُ تفكّكٍ تلت الدولة القديمة، وتشمل الأسرات (٧ – ١٠)', '');

/* ── ③ لا يُفصل: القوسُ ليس في الذيل ── */
t('رياضيّات · أقواسٌ متداخلة في المتن',
  'النقطة (-ب ÷ (٢ أ) ، د(-ب ÷ (٢ أ)))',
  'النقطة (-ب ÷ (٢ أ) ، د(-ب ÷ (٢ أ)))', '');

t('نقطتان في قوسٍ وسطيّ لا ختاميّ',
  'مركّبٌ يونانيّ (الأصل: فيلو) ومعناه حبُّ الحكمة',
  'مركّبٌ يونانيّ (الأصل: فيلو) ومعناه حبُّ الحكمة', '');

t('القوسُ الأخيرُ وحدَه مرشَّح — وهو بلا نقطتين',
  'شرحٌ (المضاد: كذا) ثمّ تتمّةٌ (١٩١٤م)',
  'شرحٌ (المضاد: كذا) ثمّ تتمّةٌ (١٩١٤م)', '');

/* ── ④ الفجوةُ النائمة: «·» داخل القوس ⇒ المتنُ يخرج متوازنَ الأقواس ── */
t('لاتينيٌّ داخل قوسِ بطاقةٍ عربيّة — ما كان backText يشطره',
  'التَّغافُلُ النَّبيل (المضاد: التَّرَصُّد · Syn: tolerance)',
  'التَّغافُلُ النَّبيل',
  'المضاد: التَّرَصُّد · Syn: tolerance');

/* ── ⑤ الحدود ── */
t('معنًى بلا قوسٍ أصلاً', 'الشَّرَفُ والحَسَب', 'الشَّرَفُ والحَسَب', '');
t('فراغ', '', '', '');
t('عدم', null, '', '');
t('فراغاتٌ حول الملحق',
  'معنًى   (المضاد: ضدّ)  ', 'معنًى', 'المضاد: ضدّ');

console.log(fail ? `\n✗ ${fail} فشلاً · ${pass} نجاحاً` : `✓ ${pass} حالةً — كلُّها تمرّ`);
process.exit(fail ? 1 : 0);
