--  ١٤٠ · محوُ المحاولات التجريبية — ليعود السؤالُ قابلاً للوسم
-- ══════════════════════════════════════════════════════════════════════
--
--  العلّة: `save_question` ترفض تعديلَ سؤالٍ أُجيب عنه («أُجيب عن هذا السؤال
--  — أنشئ نسخة جديدة من الاختبار بكود مختلف»). وأسئلةُ المنصّة مقفلةٌ كلُّها
--  تقريباً، فلا يُوسَم أيٌّ منها بهدف ⇒ **التشخيصُ بالهدف معطَّلٌ على كلّ
--  ما بُني** (١٣٩ بُني ولا يجد سؤالاً يعمل عليه).
--
--  وثلاثةُ أبوابٍ كانت مفتوحة: إرخاءُ الحارس · نسخةٌ جديدةٌ من كلّ اختبار ·
--  محوُ المحاولات. وأُقرَّ الثالثُ لأنّ المحاولاتِ كلَّها تجريبيّةٌ بشهادة
--  صاحبها — **والحارسُ يبقى كما هو**، وهو موضعُ القيمة: سؤالٌ أجاب عنه
--  طالبٌ حقيقيٌّ لا يُعدَّل أبداً، وهذا الملفّ لا يمسّ ذلك القانون بحرف.
--
--  ثلاثةُ قراراتٍ تُقرأ ولا تُستنتج:
--
--  ① **نسخةٌ قبل المحو.** جدولان جانبيّان يحملان ما حُذف. والمحوُ لا يُستردّ،
--     والشهادةُ بأنّها «تجريبية» شهادةُ إنسانٍ تُصيب وتُخطئ. فإن ظهر فيها ما
--     يُحتاج رجع من الأرشيف. ويُسقَطان متى اطمأنّ أهلُهما (آخرُ الملفّ).
--
--  ② **والأرشيفُ محميٌّ بـRLS بلا سياسة.** الجدولُ الجديد في `public` يُنشر
--     في واجهة REST تلقائياً — فأرشيفٌ بلا حمايةٍ يفتح للطلّاب إجاباتِ
--     بعضهم، وهو أسوأ ممّا جئنا نُصلح. (بلا سياسةٍ = لا أحدَ يقرأ إلا
--     `service_role`، وهو ما نريد.)
--
--  ③ **`answers` تسقط بالتعاقب** (`on delete cascade`) ولا تُحذف بيد.
--     وما سوى المحاولات لا يُمَسّ: `cards` و`card_reviews` و`item_progress`
--     و`placement_sessions` و`practice_sessions` تبقى كما هي — فالقفلُ من
--     `answers` وحدها، وما لا يلزم المسُّ به لا يُمَسّ.
--
--  وأثرُه المرئيّ: **شاشةُ «تحليل الأداء» تفرغ.** وذاك متوقَّعٌ لا عطل.
-- ══════════════════════════════════════════════════════════════════════

-- ① الأرشيف — قبل كلّ شيء
create table if not exists attempts_archive_2026_10 as select * from attempts;
create table if not exists answers_archive_2026_10  as select * from answers;

alter table attempts_archive_2026_10 enable row level security;
alter table answers_archive_2026_10  enable row level security;

revoke all on attempts_archive_2026_10 from anon, authenticated;
revoke all on answers_archive_2026_10  from anon, authenticated;

comment on table attempts_archive_2026_10 is
  'نسخةٌ من `attempts` قبل محوها في ٣ أكتوبر ٢٠٢٦ (الملفّ 140). محميّةٌ بـRLS '
  'بلا سياسة — لا يقرؤها إلا service_role. تُسقَط حين يُطمأنّ إليها.';
comment on table answers_archive_2026_10 is
  'نسخةٌ من `answers` قبل محوها في ٣ أكتوبر ٢٠٢٦ (الملفّ 140). محميّةٌ بـRLS بلا سياسة.';

-- ② المحو — و`answers` تسقط بالتعاقب
delete from attempts;

-- ③ الشهادة — تُقرأ بعد التنفيذ
select (select count(*) from attempts_archive_2026_10) as "محاولاتٌ أُرشفت",
       (select count(*) from answers_archive_2026_10)  as "إجاباتٌ أُرشفت",
       (select count(*) from attempts)                 as "محاولاتٌ باقية",
       (select count(*) from answers)                  as "إجاباتٌ باقية",
       (select count(*) from questions q
         where q.retired_at is null
           and not exists (select 1 from answers a where a.question_id = q.id))
         as "أسئلةٌ صارت قابلةً للتحرير";

insert into sql_log (n, title, applied_at)
values ('140', 'محوُ المحاولات التجريبية — ليُوسَم السؤالُ بهدفه', now())
on conflict (n) do nothing;

