-- 206 · مقرّراتُ مكتبة بيان بأسماء طبقاتها — «مكتبة بيان — البراعم»
--       (طلبُ المالك · ١٢ نوفمبر ٢٠٢٦)
--
-- لماذا:
--   ① **بطاقةُ المقرَّر في شاشة التأليف تحمل اسمَ المادّة لا عنوانَ المقرَّر** (b172 · `openEditor` في `editor.js`) —
--      فالطبقاتُ الأربع في المستوى الواحد أربعُ بطاقاتٍ كلُّها «مكتبة بيان»، لا يفرّقها شيء (لقطةُ المالك · R2).
--      والمالكُ سمّى الطبقات: **البراعم ٥–٧ · الأشبال ٨–١٠ · اليافعون ١١–١٣ · الشباب ١٤–١٨**.
--   ② **والعنوانُ يحمل الطبقةَ وحدها لا المستوى:** المستوى يُختار من قائمته فوق البطاقات، ويحمله سطرُ المقرَّر في
--      «المحتوى» وبروازُ دروسه (`courseTags`). فالعنوانُ يقول ما لا يقوله غيرُه. وكان `203` يكتب الاثنين والأعمارَ معاً.
--   ③ **ولا يتغيّر شيءٌ عند الطالب، ولا يتعطّل شيء:** شاشاتُ الطالب تعرض اسمَ المادّة لا عنوانَ المقرَّر، ولا دالّةَ ولا
--      شاشةَ تبحث عن مقرَّرٍ بعنوانه (قِيس على `sql/` و`js/`). والعناوينُ تتكرّر ٢٤ مرّةً لكلّ طبقة — ولا قيدَ على
--      العنوان؛ التفرّدُ في `courses_uniq_grades` بالمستوى والطبقة (`203` ③-ب).
--   ④ **و`author_tree` تردّ الطبقة** ⇒ البطاقةُ تعرض عنوانَ المقرَّر ذي الطبقة لا اسمَ مادّته، ومعه شارةُ أعمارها.
--      ⚠️ والأعمارُ في الشيفرة (`TIER_AGES` في `editor.js`) لا هنا — نسخةٌ ثانية من حدود الإطار §5 إلى أن تُبنى دالّةُ
--         الطبقة في المرحلة ٦، فتُقرأ الحدودُ يومها من موضعٍ واحد.
--   ⑤ ويُعاد تشغيلُه بلا أثر. و`203` و`204` عُدِّلا في اليوم نفسِه: الأوّلُ يكتب الأسماءَ الجديدة، والثاني لا يمسّ إلا
--      عنواناً يحمل الاسمَ المختلطَ القديم — فإعادةُ أيٍّ منهما لا تُرجع القديم.
-- ══════════════════════════════════════════════════════════

-- ═══════════ معدَّلة ═══════════

-- ① العناوينُ الستّةُ والتسعون — «مكتبة بيان — اسمُ الطبقة»
update public.courses c
   set title = 'مكتبة بيان — ' || t.name
  from public.subjects su,
       (values ('M1', 'البراعم'), ('M2', 'الأشبال'), ('M3', 'اليافعون'), ('M4', 'الشباب')) as t(tier, name)
 where su.code = 'sk_read' and c.subject_id = su.id
   and t.tier = c.tier
   and c.title is distinct from 'مكتبة بيان — ' || t.name;

-- ② `author_tree` تردّ الطبقة — سطرٌ بعد الشُّعبة، والدالّةُ الحيّةُ هي الأصل لا لقطة
do $$
declare v text; n int;
begin
  v := pg_get_functiondef('public.author_tree()'::regprocedure);
  if position('''tier'', c.tier' in v) > 0 then raise notice 'author_tree تردّ الطبقة من قبل'; return; end if;
  n := (select count(*) from regexp_matches(v, '''stream_id'', c\.stream_id,', 'g'));
  if n <> 1 then
    raise exception 'وُجد النمط % مرّة لا مرّةً واحدة — لا يُستبدل على الظنّ', n;
  end if;
  execute regexp_replace(v, '''stream_id'', c\.stream_id,', '''stream_id'', c.stream_id, ''tier'', c.tier,');
end $$;

-- ═══════════ الختم ═══════════

insert into public.sql_log (n, title, applied_at)
values ('206', 'مقرّراتُ مكتبة بيان بأسماء طبقاتها — «مكتبة بيان — البراعم»', now())
on conflict (n) do update set applied_at = now();
