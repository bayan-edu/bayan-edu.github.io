/* ═══════════════════════════════════════════════════════════════════
   169 · حارسُ الرفع يعود يُنادى — منحُ `can_upload_media()` للمسجَّلين

   لماذا:
   🔴 **عطلٌ صامتٌ منذ `154`:** إحكامُ `EXECUTE` سحب المنحَ عن الدوالّ
      إلا ما سُمّي، **ولم تُسمَّ `can_upload_media`** — وهي التي تناديها
      سياساتُ المخزنين الثمانية (`audio_*` · `img_*` على `storage.objects`).
      والسياسةُ تُنفَّذ بدور المستدعي (`authenticated`)، فيسقط كلُّ رفعٍ
      من المحرّر بـ`42501 permission denied` — **والمديرُ نفسُه يُردّ.**
      🧪 قِيس على الحيّ (٢٠ أكتوبر) بهويّة المدير الوحيد:
         `is_admin()` ⇒ true · `can_upload_media()` ⇒ ERR 42501
      ولم يظهر لأنّ أحداً لم يرفع منذئذٍ: آخرُ ملفٍّ في `audio` يوم
      ٥ سبتمبر، و`img` وُلد بعد `154` ولم يدخله ملفٌّ قطّ. وقياسُ `160`
      جرى بدور `postgres` — **فشهد للبنية لا للصلاحية**، وقالها صراحةً.

   ✅ **والدالّةُ الطرفيّة `r2-sign` تناديها أيضاً** بهويّة المستدعي —
      فهي حارسُ الرفع الواحد للبيتين (Supabase وR2)، **لا مسطرتان.**

   🔑 **ولماذا المنحُ آمن:** الدالّةُ لا تقرأ صفّاً ولا تكشف شيئاً؛ تقول
      للمستدعي «أأنت مأذونٌ بالرفع؟» عن نفسه وحدها (`is_admin()` بهويّته).
      و`is_admin()` التي تتّكئ عليها ممنوحةٌ أصلاً لـ`anon` و`authenticated`.
      ⚠️ **ولـ`authenticated` وحده لا `anon`:** الزائرُ لا يرفع، فلا يسأل.

   ⚙️ قابلٌ لإعادة التشغيل: المنحُ القائمُ لا يُكرَّر.
   ═══════════════════════════════════════════════════════════════════ */

begin;

/* ──────────────────── منحٌ لا منشأ ──────────────────── */

grant execute on function public.can_upload_media() to authenticated;

/* ───────────────────────── السجلّ ───────────────────────── */

insert into public.sql_log (n, title, applied_at)
values ('169', 'حارسُ الرفع يعود يُنادى — منحُ can_upload_media() للمسجَّلين', now())
on conflict (n) do update set applied_at = now();

commit;

/* ─────────── الفحص — جملةٌ واحدة: المنحُ قائمٌ ولـanon لا ─────────── */

select has_function_privilege('authenticated', 'public.can_upload_media()', 'execute') as المسجَّل,
       has_function_privilege('anon',          'public.can_upload_media()', 'execute') as الزائر_يجب_false;
