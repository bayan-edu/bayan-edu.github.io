-- ═══════════ معدَّلة ═══════════

-- ① الأسماءُ الستّة — والمقابلةُ كلُّها من الإطار §3: R1–R5 Pre-A1 · R6–R11 A1 · R12–R16 A2 · R17–R20 B1 · R21–R23 B2 · R24 C1 (entry)
update public.levels lv
   set name = 'R' || lv.rank || ' · ' || case when lv.rank <=  5 then 'Pre-A1'
                                              when lv.rank <= 11 then 'A1'
                                              when lv.rank <= 16 then 'A2'
                                              when lv.rank <= 20 then 'B1'
                                              when lv.rank <= 23 then 'B2'
                                              else 'C1 (entry)' end
  from public.scales sc
 where sc.id = lv.scale_id and sc.code = 'reading'
   and lv.name is distinct from 'R' || lv.rank || ' · ' || case when lv.rank <=  5 then 'Pre-A1'
                                                                when lv.rank <= 11 then 'A1'
                                                                when lv.rank <= 16 then 'A2'
                                                                when lv.rank <= 20 then 'B1'
                                                                when lv.rank <= 23 then 'B2'
                                                                else 'C1 (entry)' end;

-- ② عناوينُ المقرّرات من الاسم الجديد — بصيغة `203` ④ نفسِها: «مكتبة بيان — المستوى · الطبقة (أعمارُها سنوات)»
update public.courses c
   set title = 'مكتبة بيان — ' || lv.name || ' · ' || c.tier || ' (' || t.ages || ' سنوات)'
  from public.subjects su, public.levels lv, public.scales sc,
       (values ('M1', '٥–٧'), ('M2', '٨–١٠'), ('M3', '١١–١٣'), ('M4', '١٤–١٨')) as t(tier, ages)
 where su.code = 'sk_read' and c.subject_id = su.id
   and lv.id = c.level_id and sc.id = lv.scale_id and sc.code = 'reading'
   and t.tier = c.tier
   and c.title is distinct from 'مكتبة بيان — ' || lv.name || ' · ' || c.tier || ' (' || t.ages || ' سنوات)'
   -- 📌 لا يمسّ إلا عنواناً يحمل الاسمَ المختلطَ القديم: `206` سمّى المقرّراتِ بطبقاتها، فإعادةُ هذا الملفّ بعده تمضي بلا أثر
   and (c.title like '%قبل A1%' or c.title like '%مدخل C1%');

