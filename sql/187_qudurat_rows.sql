-- ══════════════════════════════════════════════════════════════════════
--
--  الخطوةُ ٤ من `spec-content-layers.md` (§٥ · §٨): البنيةُ بُنيت في 183 و184 و185، وهذه صفوفُها
--  للمادّة ٤٧. **بياناتٌ لا شيفرة** (§٩-١): لا دالّةَ تُمسّ، ولا جدولَ يُنشأ، ولا منحَ يتغيّر.
--
--  وستّةُ أحكامٍ تُقرأ ولا تُستنتج:
--
--  ① **الشعبتان كما تقسمهما الهيئة بنصّها** — «الدليل الإرشادي لاختبار القدرات العامة» (هيئة تقويم
--     التعليم والتدريب · media.etec.gov.sa · نسخةُ ٢٣ يوليو ٢٠٢٦ · ص٤): «للتخصصات العلمية، لطلاب وطالبات
--     المسار العام، ومسار علوم الصحة والحياة، ومسار علوم الحاسب والهندسة» · «للتخصصات النظرية، لطلاب
--     وطالبات المسار الشرعي، ومسار إدارة الأعمال». **وأسماءُ المسارات أسماؤها في الدليل** لا اختصارُها في
--     الوثيقة («الصحة والحياة» ⇐ «علوم الصحة والحياة»). والكلمةُ المعروضة «التخصص» (ق٢).
--  ② **سطرُ ق١ في عون العلمي:** «وإن لم يتحدّد مسارك بعد فهو الأنسب: يجمع المهارات كلّها» — فالعلميُّ
--     يقيس الفروعَ الثمانية، والنظريُّ سبعةً بلا جبر (④). **وبالكاف لا بالمضارع المخاطب:** «إن لم تحدّد»
--     في الوثيقة يفرض المذكّر (مهارةُ الهويّة §٤). **وبلا «والتغييرُ لا يضيع شيئاً»:** الشاشةُ تقولها تحت
--     الخيارين بحرفها (`askStream` · «يمكنك تغيير اختيارك لاحقاً، ولا يضيع ما أنجزته»).
--  ③ **٤٣ بيتُ العلمي** («القدرات · علمي») بوحداته الاثنتي عشرة كما هي، **والنظريُّ مقرَّرٌ جديد:**
--     «اختبار البداية» و«اختبارات المحاكاة» وحدتاه هو — نموذجاه غيرُ نموذجَي العلمي — والتسعُ بينهما
--     سطورُ استعارةٍ من ٤٣ بمواضعها (٢–١٠). و«الجبر · للتخصص العلمي» (١١) لا تُستعار: النظريُّ بلا جبر.
--     والتسعُ بمعرّفاتها لا بمواضعها، ويُفحص أنّها في ٤٣ بمواضعها قبل الاستعارة — فلا يُستعار على الظنّ.
--  ④ **الأوزانُ أوزانُ الهيئة بحرفها** (الدليل · ص٥: «وتمثل المجالات السابقة في الاختبار بنسب محدّدة»)
--     — لكلّ فرعٍ ورقةٍ في كلّ شعبة، ومجموعُ كلٍّ منهما ١٠٠:
--
--       الفرع              علمي   نظري        الفرع            علمي   نظري
--       استيعاب المقروء     ٢١     ٢٥          الحساب            ٢٣     ١٣
--       التناظر اللفظي      ١٧     ٢١          الهندسة           ١٠     ٨
--       الخطأ السياقي       ١٠     ١٦          تفسير البيانات    ٨      ٤
--       إكمال الجمل         ٧      ١٣          الجبر             ٤      —
--
--     🔴 **وقُرئ الجدولُ من مواضع الحروف لا من نصّه المستخرَج:** استخراجُ النصّ العربيّ يقلب أرقامَه
--        («%12%71» للتناظر)، فبُنيت الأرقامُ من مواقعها على الصفحة وتحت رؤوس أعمدتها — والعمودان يبلغان
--        ١٠٠ تماماً، والجبرُ «=» في النظريّ. 📌 **ووثيقةُ الطبقات (§٨) كانت تقول إنّ الأوزانَ يكتبها معلّما
--        القدرات** — والهيئةُ نشرتها، فهي هي. وما يكتبه المعلّمان البنوكُ الثمانية.
--  ⑤ **يُعاد تشغيلُه ولا يُعيد ما حُرّر بعده:** الشعبةُ والوزنُ `on conflict do nothing`، والمقرَّرُ والوحدتان
--     والسطورُ `where not exists` — فما يعدّله المشرفُ بعدُ في الإدارة لا يعود إلى أصله إن أُعيد الملفّ.
--     وتسميةُ ٤٣ مرّةً واحدة ما دام بلا شعبة، والكلمةُ المعروضة ما دامت فارغة.
--  ⑥ **وما يراه الطالب:** حسابٌ واحدٌ على سلّم القدرات اليوم (التجريبيّ `b4dda1fe…` — قِيس). يُسأل «اختيار
--     التخصص» أوّلاً، ثمّ «قيد الإعداد» ما دامت الدروسُ لم تُنشر — وهو حدُّ `183` ① بعينه، يُقرَّر في الواجهة.
--
--  📐 وما ليس هنا عمداً:
--  · البنوكُ الثمانية والنماذجُ الأربعة — محتوًى يكتبه معلّما القدرات (§٥ · §٨).
--  · حدُّ `183` ①: بطاقةُ مادّةٍ ذاتِ شعبٍ مقرَّرُ شعبتها فارغ لا تُنقر، فلا يبلغ الطالبُ سطرَ التغيير — واجهةٌ.
-- ══════════════════════════════════════════════════════════════════════


-- ═══════════════════ ① المادّة وشعبتاها (رأس الملفّ ① ②) ═══════════════════

update public.subjects set stream_label = 'التخصص'
 where id = 47 and stream_label is null;

insert into public.streams (subject_id, code, name, hint, sort_order) values
  (47, 'sci',  'علمي',
   'المسار العام، ومسار علوم الصحة والحياة، ومسار علوم الحاسب والهندسة. وإن لم يتحدّد مسارك بعد فهو الأنسب: يجمع المهارات كلّها.', 1),
  (47, 'theo', 'نظري',
   'المسار الشرعي، ومسار إدارة الأعمال.', 2)
on conflict (subject_id, code) do nothing;


-- ═══════════════════ ② المقرَّران (رأس الملفّ ③) ═══════════════════

-- ٤٣ بيتُ العلمي — يُسمّى ويُوسَم مرّةً واحدة
update public.courses c
   set title = 'القدرات · علمي',
       stream_id = (select s.id from public.streams s where s.subject_id = 47 and s.code = 'sci')
 where c.id = 43 and c.subject_id = 47 and c.stream_id is null;

-- والنظريُّ مقرَّرٌ جديد في موضع ٤٣ — بلا صفٍّ ولا مسارٍ مثله، فيقوم بجواره بالشعبة وحدها (`courses_uniq_stream`)
insert into public.courses (subject_id, level_id, path_id, title, position, active, stream_id)
select 47, null, null, 'القدرات · نظري', c43.position, true, s.id
  from public.streams s, public.courses c43
 where s.subject_id = 47 and s.code = 'theo' and c43.id = 43
   and not exists (select 1 from public.courses c where c.subject_id = 47 and c.stream_id = s.id);


-- ═══════════════════ ③ وحدتا النظريّ وسطورُه التسعة (رأس الملفّ ③) ═══════════════════

insert into public.units (course_id, title, position)
select t.id, x.title, x.pos
  from public.courses t
  join public.streams s on s.id = t.stream_id and s.subject_id = 47 and s.code = 'theo',
       (values ('اختبار البداية', 1), ('اختبارات المحاكاة', 11)) x(title, pos)
 where not exists (select 1 from public.units u where u.course_id = t.id and u.title = x.title);

do $$
begin
  if (select count(*) from public.units
       where course_id = 43 and position between 2 and 10
         and id in (141, 132, 130, 137, 136, 134, 135, 133, 139)) <> 9 then
    raise exception '187: وحداتُ ٤٣ التسع ليست في مواضعها (٢–١٠) — لا يُستعار على الظنّ';
  end if;
end $$;

-- والسطرُ بموضع الوحدة في بيتها — فالترتيبُ في المقرَّرين واحد، وحارسُ 184 يحكم كلَّ سطر
insert into public.unit_links (course_id, unit_id, position)
select t.id, u.id, u.position
  from public.courses t
  join public.streams s on s.id = t.stream_id and s.subject_id = 47 and s.code = 'theo'
  join public.units u on u.course_id = 43 and u.id in (141, 132, 130, 137, 136, 134, 135, 133, 139)
 where not exists (select 1 from public.unit_links l where l.course_id = t.id and l.unit_id = u.id);


-- ═══════════════════ ④ أوزانُ الهيئة (رأس الملفّ ④) ═══════════════════

insert into public.stream_weights (stream_id, strand_id, pct)
select s.id, t.id, w.pct
  from (values ('sci',  'RC', 21), ('sci',  'ANA', 17), ('sci',  'CTX', 10), ('sci',  'SEN',  7),
               ('sci',  'ARI', 23), ('sci',  'GEO', 10), ('sci',  'DAT',  8), ('sci',  'ALG',  4),
               ('theo', 'RC', 25), ('theo', 'ANA', 21), ('theo', 'CTX', 16), ('theo', 'SEN', 13),
               ('theo', 'ARI', 13), ('theo', 'GEO',  8), ('theo', 'DAT',  4)) w(stream, strand, pct)
  join public.streams s on s.subject_id = 47 and s.code = w.stream
  join public.strands t on t.subject_id = 47 and t.code = w.strand
on conflict (stream_id, strand_id) do nothing;

-- وحارسُ 185 يمنع ما فوق المئة، وهذا يمنع ما دونها: وزنٌ ضاع بكودٍ لا فرعَ له يُرى هنا لا في العدّاد
do $$
begin
  if exists (select 1 from public.streams s
              where s.subject_id = 47
                and (select coalesce(sum(w.pct), 0) from public.stream_weights w where w.stream_id = s.id) <> 100) then
    raise exception '187: أوزانُ شعبةٍ في القدرات لا تبلغ ١٠٠';
  end if;
end $$;


