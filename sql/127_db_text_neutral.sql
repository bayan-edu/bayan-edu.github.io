-- 127 · تحييدُ نصوص القاعدة — إتمامُ ما بدأ في الواجهة
--
-- حُيّدت نصوصُ `js/` (b97): سبعةٌ وتسعون موضعاً في تسعة عشر ملفاً. **وبقي
-- ما يسكن القاعدة** — سبعةَ عشرَ نصّاً في ثلاث عشرة دالّة، يراها المستخدمُ
-- كما يرى تلك. وحُصر القياسُ الأوّل في `js/` كما حصرته الخطّة، فسقطت.
--
-- 🔑 **والنصُّ وحده يُستبدَل — لا الدالّة.** ثلاث عشرة دالّةً تُنسخ باليد،
--    وفيها `save_item` بستّة عشر وسيطاً و`save_quiz` بخمسة عشر — **وهو
--    فخُّ ٥ سبتمبر بعينه**: قُرئ يومها `00_schema.sql` فاستُبدلت دوالُّ
--    بنسخٍ أقدم، فسقط نمطُ `gap` والإعدادات، ولم يظهر إلا عند المعلّم.
--    ⇒ يُقرأ التعريفُ الحيُّ بـ`pg_get_functiondef`، ويُستبدَل فيه النصُّ
--      المقصود وحده، ثمّ يُنفَّذ كما هو. **فما لم يُقصد لا يتغيّر بتةً،
--      ولا فرصةَ لخطأ نسخٍ أصلاً.**
--
-- 🔑 **وقابلٌ لإعادة التشغيل بطبعه:** الاستبدالُ لا يجد النصَّ القديم في
--    المرّة الثانية، فلا تُلمَس دالّةٌ ولا يُنفَّذ شيء.
--
-- ⚠️ **ولا يُمَسّ `tool_readiness`** وإن التقطه المِسبار: «مدَيان
--    متداخلان» مثنّى `مدًى` لا مخاطبةَ فيه. **والمِسبارُ يلتقط الشكلة،
--    والحكمُ للقارئ.**
--
-- 📌 **ومنهجُ التحييد كما في الواجهة:** يُسمّى الناقصُ («الاسم الكامل
--    مطلوب») أو يُبنى للمجهول («يُختار فرعٌ نهائيّ») — ولا يُكتب بصيغتين،
--    فالنصُّ يصير استمارة. وحيث أمكنت المحايدةُ **لم تُستدعَ صيغة**.
-- ═══════════════════════════════════════════════════════════════════════

set check_function_bodies = off;

create temp table if not exists _neut_log(fn text, args text);

do $$
declare
  /* [القديم, الجديد] — والقديمُ منسوخٌ من `prosrc` الحيّ بحرفه */
  pairs text[] := array[
    'اكتب الكلمة أولاً',                                   'الكلمة أولاً',
    'اكتب معنى الكلمة — فهي جديدةٌ عليك وعلى المنصّة',      'معنى الكلمة مطلوب — فهي جديدةٌ عليك وعلى المنصّة',
    'انسخ الاختبار بكود جديد',                             'ويُنسخ الاختبار بكود جديد',
    'استفدتَ من فرص الانتقال المتاحة في هذه المادة. ',      'استُوفيت فرصُ الانتقال في هذه المادة. ',
    'نرجو أن تعرض ما يشكل عليك على معلمك الحالي — ',        'وما يشكل عليك يُعرَض في المراسلة — ',
    'فالاستمرار معه أنفع لمتابعة تقدّمك.',                  'فهي أقربُ من الانتقال.',
    'أعد وسمها أولاً',                                     'ويُعاد وسمُها أولاً',
    'أكمل أولاً: ',                                        'يسبقه: ',
    'افتح رابطَ التحقّق المرسَل إلى بريدك، ثمّ أعد المحاولة', 'يُفتح رابطُ التحقّق المرسَل إلى بريدك، ثمّ تُعاد المحاولة',
    'أعد فتح رابط التحقّق من بريدك',                        'ويُعاد فتح رابط التحقّق من بريدك',
    'اكتب اسمك الكامل',                                    'الاسم الكامل مطلوب',
    'اختر مادّةً من القائمة',                               'مادّةٌ من القائمة مطلوبة',
    'اختر فرعاً نهائياً: «جبر» لا «بحتة»',                   'يُختار فرعٌ نهائيّ: «جبر» لا «بحتة»',
    'اختر دور المحطّة في التوجيه',                          'دورُ المحطّة في التوجيه مطلوب',
    'اختر صفّك في ',                                       'يُختار صفُّك في ',
    ' — اخترتَ ',                                          ' — والمختارُ ',
    'أبطئ قليلاً ثمّ أعد المحاولة',                         'الطلبُ أسرعُ من المسموح — تُعاد المحاولة بعد قليل'
  ];
  r record; def text; nd text; i int;
begin
  for r in
    select p.oid, p.proname, pg_get_function_identity_arguments(p.oid) as args
    from pg_proc p join pg_namespace n on n.oid = p.pronamespace
    where n.nspname = 'public' and p.prokind = 'f'
  loop
    def := pg_get_functiondef(r.oid);
    nd  := def;
    i := 1;
    while i < array_length(pairs, 1) loop
      nd := replace(nd, pairs[i], pairs[i+1]);
      i := i + 2;
    end loop;

    if nd is distinct from def then
      execute nd;
      insert into _neut_log values (r.proname, r.args);
    end if;
  end loop;
end $$;


