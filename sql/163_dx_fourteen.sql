-- ─── ② الترحيل — الخرائط والإجابات ───────────────────────────────────────

-- dx_map: قيمةٌ قديمة ⇒ جديدة، والمفاتيح (معرّفات الخيارات) كما هي
update question_keys k
   set dx_map = (select jsonb_object_agg(e.key, coalesce(m.new, e.value))
                   from jsonb_each_text(k.dx_map) e
                   left join dx_163_map m on m.old = e.value)
 where k.dx_map is not null
   and exists (select 1 from jsonb_each_text(k.dx_map) e
                join dx_163_map m on m.old = e.value);

-- wrong_map (أسئلة الفراغ والاختيار المتعدّد): القيم أكوادٌ كذلك
update question_keys k
   set wrong_map = (select jsonb_object_agg(e.key, coalesce(m.new, e.value))
                      from jsonb_each_text(k.wrong_map) e
                      left join dx_163_map m on m.old = e.value)
 where k.wrong_map is not null
   and exists (select 1 from jsonb_each_text(k.wrong_map) e
                join dx_163_map m on m.old = e.value);

-- answers: أربعة صفوفٍ يوم الكتابة — تُرحَّل لأنّها مفتاحٌ أجنبيّ
update answers a
   set dx_code = m.new
  from dx_163_map m
 where a.dx_code = m.old;


-- ─── ③ ثلاث دوالّ تكتب HLF و PRC حرفياً — معدَّلة ─────────────────────────
-- submit_attempt:          case_slip ⇒ 'PRC' · hits > 0 بلا كود ⇒ 'HLF' (×3)
-- submit_practice_answer:  النمط نفسه (×1 · ×2)
-- practice_snapshot_quiz:  dx_extra تحمل نصَّي ('PRC','HLF') لمن يقع فيهما
-- تُقرأ الحيّة بـ pg_get_functiondef وتُستبدل الحرفيّتان لا غير — بحارسٍ
-- يرفض الدالّة إن حملت كوداً حرفياً ثالثاً (قِيس: لا ثالثَ فيها اليوم).

do $$
declare r record; v text; n_prc int; n_hlf int;
begin
  for r in
    select p.oid::regprocedure as sig
      from pg_proc p join pg_namespace n on n.oid = p.pronamespace
     where n.nspname = 'public'
       and p.proname in ('submit_attempt', 'submit_practice_answer', 'practice_snapshot_quiz')
  loop
    v     := pg_get_functiondef(r.sig);
    n_prc := (length(v) - length(replace(v, '''PRC''', ''))) / 5;
    n_hlf := (length(v) - length(replace(v, '''HLF''', ''))) / 5;
    if n_prc + n_hlf = 0 then
      raise notice '163: % — لا حرفيّة فيها (صُحّحت من قبل)', r.sig;
      continue;
    end if;
    if exists (select 1 from regexp_matches(v, '''([A-Z][A-Z0-9]{1,3})''', 'g') as m
                where m[1] not in ('PRC', 'HLF')) then
      raise exception '163: % تحمل كوداً حرفياً غير PRC/HLF — تُراجَع يدوياً قبل الاستبدال', r.sig;
    end if;
    v := replace(replace(v, '''PRC''', '''FORM'''), '''HLF''', '''PART''');
    execute v;
    raise notice '163: % — PRC×% ⇒ FORM · HLF×% ⇒ PART', r.sig, n_prc, n_hlf;
  end loop;
end $$;


