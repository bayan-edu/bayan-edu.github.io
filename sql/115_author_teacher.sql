-- 115 · التأليف يبلغ المعلّم — في مادّته وحدها
--
-- كانت can_author تقول `select can_curate(p_subject)` وتحمل تحتها تعليقاً:
-- «غداً: select can_curate(p_subject) or is_teacher()». وهذا الملفّ ذلك
-- الغد — بغير ذاك المسند.
--
-- 🔴 ولماذا كان لا بدّ منه: curators جدولٌ فارغ (٠ صفّ) ⇒ can_curate =
--    is_admin() حرفياً ⇒ **can_author = is_admin()**. فالمعلّمون الثلاثة
--    لا يملكون تأليف حرفٍ واحد، وتصديقُ ذلك في الأرقام: ١٦ مصدراً كلُّها
--    created_by فارغ، وصفرُ دروسٍ ألّفها غيرُ المدير. **بابٌ موصَدٌ لا
--    شكوى له** — لأنّ الشاشة تقول «لا تملك التأليف في هذه المادة»،
--    فيُقرأ منعاً مقصوداً لا قفلاً مؤقّتاً.
--
-- 🔑 ولماذا ليس `or is_teacher()` كما في التعليق: مطلقةً تمنح كلَّ معلّمٍ
--    تأليفاً في إحدى وعشرين مادّة، فيها ما لا يُدرّسه ولا يعرفه. والقيدُ
--    هنا teacher_subjects — **المادّةُ التي أعلن أنّه يُدرّسها** — وهي
--    الجدول الذي عليه سعتُه وقبولُه للطلاب، فالإعلانُ فيه قائمٌ أصلاً
--    ولا يُنشأ له إعلانٌ ثانٍ.
--
-- 🔑 وليس هذا تغييراً في البنية بل تشغيلُ ما بُنيت له. القسمة مرسومةٌ في
--    المخطّط منذ أوّله، وقُرئت من الحيّ لا من لقطة:
--      can_curate → الهيكل : save_lesson · publish_lesson · save_strand · save_card
--      can_author → الحشو  : save_item · save_question · save_quiz · author_tree
--    ⇒ المعلّم **يُثري داخل درسٍ قائم ولا يُنشئ درساً ولا ينشره**. وهو
--    بحرفه ما كُتب في رأس js/editor_items.js منذ أن كُتب:
--    «إضافات المعلمين — إثراء لا يحجب · باسم مؤلّفه».
--
-- ⚠️ ويبقى is_teacher() حارساً وإن بدا أنّ EXISTS يُغني عنه: صفٌّ في
--    teacher_subjects يقول «سعةٌ وقبولُ طلاب»، لا يقول «له أن يؤلّف».
--    فلو سقط الدورُ عن صاحبه وبقي صفُّه لَمَا جاز أن يبقى التأليف.
--
-- 📌 ولا سياسةَ RLS واحدة تستعمل can_author — فُحص pg_policy كلُّه قبل
--    التوسيع. ستُّ دوالِّ تأليفٍ تستعملها، وهي المقصودة. ⇒ لا يفتح هذا
--    الملفُّ بابَ قراءةٍ على بيانات أحد.
--
-- 🔒 وما لم يتغيّر: المدير وحده يمنح الدور `teacher` (admin_decide)،
--    وبوابةُ التسجيل كما هي. **توسيعُ ما يفعله المعلّمُ المعتمَد ليس
--    توسيعاً لمن يصير معلّماً** — وذاك قرارٌ آخر لم يُتَّخذ بعد.
-- ═══════════════════════════════════════════════════════════════════════

set check_function_bodies = off;


-- ═══════════════════════════════════════════════════════════════════════
-- ① معدَّلة لا منشأة — can_author
--    قُرئت حيّةً بـ pg_get_functiondef قبل الاستبدال (⓪·ب ①)، والفرق
--    مسنَدٌ واحد يُضاف. وما عداه محفوظٌ بحرفه: sql · stable ·
--    security definer · search_path = 'public'.
-- ═══════════════════════════════════════════════════════════════════════

create or replace function public.can_author(p_subject bigint)
returns boolean language sql stable security definer set search_path to 'public'
as $function$
  select can_curate(p_subject)
      or (is_teacher()
          and exists (select 1 from teacher_subjects t
                       where t.teacher_id = auth.uid()
                         and t.subject_id = p_subject));
$function$;

-- المنح: تُعاد صريحةً وإن حفظها create or replace — فالملفّ يُشغَّل
-- وحده يوماً، والقسم ⑧ في المخطّط يسحب الافتراضيّ. وهي نفسُ ما كان
-- على الدالّة قبل الاستبدال، لا زيادةَ فيها: anon يستدعيها فتُرجع
-- false دائماً (auth.uid() فارغ)، وسحبُه قرارٌ آخر لا يُدسّ هنا.
grant execute on function public.can_author(bigint)
  to anon, authenticated, service_role;


