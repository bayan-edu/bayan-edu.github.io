-- ══════════════════════════════════════════════════════════════════════
--
--  قرارُ المالك (٢٤ أكتوبر): «أعتمد خطّة الطريق الحيّ بالقرارات الافتراضيّة» —
--  طلبُ النصوص يقرأ حالةَ المقرّر من القاعدة كما تقرؤها طلباتُ الاختبار
--  (`R4.3` · مهارةُ البطاقات)، لا من `courses.json` في مجلّد كلّ صفّ.
--
--  🔑 **ولماذا الحقل:** النصُّ يُعرف **بعنوانه في درسه** (`import_texts` · 180).
--     ومؤلّفٌ لا يرى العنوانَ القائمَ يكتب غيرَه بحرف — **فيُنشأ نصٌّ ثانٍ بجوار
--     الأوّل** ويقرأ الطالبُ نصّين. و`144` حملت كلَّ ما يُؤلَّف عليه إلا هذا.
--  🔑 **ولماذا الحيّ لا الملفّ:** ملفُّ الحالة للمقرّرات المفعّلة بلغ ١٫٥ ميجابايت
--     (٢٤ أكتوبر)، ويُولَّد لكلّ صفٍّ على حدة، ويَبلى بأوّل استيراد — وهي علّتا
--     `144` بعينهما، وقد كبرتا.
--
--  وخمسةُ قرارات تُقرأ ولا تُستنتج:
--
--  ① **منقولٌ لا مُؤلَّف** (`144` · ①): التعبيرُ هو ⑥ في `tools/state.sql` حرفاً —
--     الرسميُّ وحده (`created_by is null`) بعنوانه ولغته، وبترتيبه في الدرس.
--  ② **إضافةٌ لا استبدال** (`145` · ①): كلُّ حقلٍ قائمٍ كما هو، وقارئٌ لا يعرف
--     `texts` لا يتغيّر عليه شيء.
--  ③ **ترقيعٌ في الحيّة لا نسخٌ لها** (مهارةُ الانضباط · §٣): الدالّةُ لا تُنسخ
--     كاملةً هنا فتتجمّد على يوم النسخ. والمرسى `and i.quiz_id is not null)))` —
--     ختامُ `questions` وختامُ كائن الدرس — **قِيس مرّةً واحدةً في الحيّة (٢٤ أكتوبر).**
--     وصفرُ مطابقاتٍ مع حقلٍ قائم ⇒ يُخبر ويمضي (الملفُّ يُعاد تشغيلُه)، وأيُّ عددٍ
--     آخر ⇒ استثناءٌ ولا يُكتب شيء.
--  ④ **المنحُ كما هو** (`154`): `postgres` و`service_role` وحدهما. فالدالّةُ لا
--     تناديها الواجهة، ومشروعُ المادة يبلغها بموصول القاعدة ومطالبِ هويّةٍ تُرضي
--     `can_author` داخلها. و`create or replace` يُبقي المنحَ القائم — فلا `grant` هنا.
--  ⑤ **الدرسُ بلا نصٍّ يحمل `[]` لا `null`:** فيُفرَّق «لا نصَّ له» عن «حقلٌ غائب»
--     — وهو الفرقُ الذي يردّ به `make_requests.py` ملفَّ حالةٍ قديماً.
-- ══════════════════════════════════════════════════════════════════════


-- ═══════════════════ معدَّلةٌ لا منشأة ═══════════════════

do $$
declare
  v text; n int;
  c_anchor constant text := 'and i.quiz_id is not null)))';
  c_new    constant text := $t$and i.quiz_id is not null)),
        'texts', coalesce((select jsonb_agg(jsonb_build_object(
                     'title', i.title, 'lang', i.lang) order by i.position, i.id)
                    from items i
                   where i.lesson_id = le.id and i.kind = 'text'
                     and i.created_by is null), '[]'::jsonb))$t$;
begin
  v := pg_get_functiondef('public.course_state(bigint)'::regprocedure);   -- الحيّةُ لا اللقطة
  n := (length(v) - length(replace(v, c_anchor, ''))) / length(c_anchor);

  if n = 0 and position('''texts''' in v) > 0 then
    raise notice '181: حقلُ texts قائمٌ في course_state من قبل — لا تغيير';
    return;
  end if;
  if n <> 1 then
    raise exception '181: وُجد المرسى % مرّةً لا مرّةً واحدة — لا يُرقَّع على الظنّ', n;
  end if;

  execute replace(v, c_anchor, c_new);
end $$;

