-- 123 · صيغةُ المخاطبة — إعدادٌ نحويّ لا سمةٌ ديموغرافية
--
-- العربية تُلزم بالاختيار في كلّ مخاطبة: «أحسنتَ» أم «أحسنتِ». والبدائل
-- كلُّها مكلفة — الافتراضُ المذكّر يُخاطئ نصفَ الطلاب في كلّ تفاعل،
-- والصياغةُ المحايدة تُجمّد صوتَ بيان، وكتابةُ الصيغتين معاً تجعل النصَّ
-- استمارة. **والطالبةُ التي تُخاطَب «أحسنتَ» مئةَ مرّة تتعلّم بهدوءٍ أنّ
-- المنصّة لم تُبنَ لها.**
--
-- 🔑 **والاسمُ مقصود: `gram_gender` لا `gender`.** من يقرأ المخطَّط بعد
--    سنةٍ يعرف من الاسم وحده أنّ هذا **إعدادٌ نحويّ للمُخاطَب** لا صفةٌ
--    عن صاحبه، فلا يُغرى باستعماله في غير موضعه. (وهو تأطيرُ أندرويد ١٤
--    في Grammatical Inflection API بحرفه: «الجنسُ النحويُّ للمُخاطَب».)
--
-- ⛔ **الخطُّ الأحمر — ولا يُوسَّع `role`.** لو صار
--    `student_m · student_f · teacher_m · teacher_f` **لسقطت `is_teacher()`
--    أوّلاً** — وهي حارسُ `security definer` تتّكئ عليه سياساتُ RLS —
--    ومعها عدُّ الطلاب وقائمةُ المعلمين وسياسةُ `p_msg_send` ودالّةُ
--    الترقية. **مكسبٌ لغويٌّ ثمنُه ثقبٌ أمنيّ.** ⇒ عمودان متعامدان:
--    `role` للصلاحية، و`gram_gender` للنصّ، ولا يُقرأ أحدهما مكان الآخر.
--
-- 🔑 **ويقبل `null` ولا افتراضَ مذكّر.** التسعةَ عشرَ القائمون لم يُسألوا،
--    فلا تُنسَب إليهم صيغةٌ لم يختاروها: **نسبةٌ عن أحدٍ أسوأ من غيابها**
--    (نظيرُ ١٢١ في الموافقة). ومستوى النصّ يعامل الغيابَ بالمحايدة كتابةً،
--    ثمّ يُسأل صاحبُ الحساب مرّةً واحدة من قائمة الحساب.
--
-- ⚠️ **و`handle_new_user` لم تُمَسّ — قصداً يُكتب لا سهواً.** هي المحفِّز
--    الذي يعبره كلُّ تسجيل، وخطأٌ فيها يُغلق البابَ على الجميع. والقيمةُ
--    لا تحتاجها: بين التسجيل وتأكيد البريد **لا جلسةَ أصلاً**، فتعبر
--    القيمةُ في `raw_user_meta_data` ويختمها `boot` عند أوّل دخول —
--    وهو بالضبط مسلكُ `policy_version` (١٢١) و`scale_id`. **مسلكٌ قائمٌ
--    مُجرَّبٌ آثرُ من محفِّزٍ يُستبدل.**
--
-- ⚠️ **والقيدُ الدائم: تُقرأ من طبقة النصّ وحدها.** لا من اختيار المحتوى،
--    ولا من محرّك التشخيص، ولا تقسيماً افتراضياً في التحليلات. والجنسُ
--    كسمةٍ ديموغرافية لا يتنبّأ بشيءٍ قابلٍ للتصرّف عن **هذا** الطالب
--    بعينه — والتباينُ داخل المجموعة يبتلع الفرقَ بين المجموعتين. ولو
--    فرّع النظامُ يوماً محتوًى أو توقّعاً عليه **لزاحم `dx_codes`**، وهي
--    الأداةُ الشرعية الوحيدة لتحديد ما يحتاجه الطالب تالياً.
--
-- 📌 **ولا دالّةَ لهذا العمود — ومنحٌ عموديّ يكفي (على غرار ٥٠).** القيدُ
--    هو كلُّ التحقّق المطلوب، فلا حكمَ تحرسه دالّة. وهذا يفرّقه عن
--    `accept_policy`: هناك حكمٌ («أوّلُ موافقةٍ تُصان») فاحتاج دالّة،
--    وهنا لا حكم. **ودالّةٌ بلا حكمٍ طبقةٌ تُصان بلا مقابل.**
-- ═══════════════════════════════════════════════════════════════════════


